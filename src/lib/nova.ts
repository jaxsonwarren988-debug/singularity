/** Local KALMIA + NOVA intelligence: handles screen inspection, autonomous work, math, essays, code, and OS control. */
export function novaRespond(raw: string, attachVision = false): NovaReply {
  const q = raw.trim();
  const t = q.toLowerCase();
  const os = useOS.getState();
  const ui = useUI.getState();
  const prof = os.session ? os.db.profiles[os.session] : null;
  const persona = prof?.settings.aiPersona || "kalmia";
  const actions: AIActionBadge[] = [];

  if (!t) return { text: "Give me a task, question, or screen to inspect — I'm ready." };

  // 1. Screen / Workspace Vision Inspection
  const wantsScreen = attachVision || /(see my screen|what.*on my screen|look at.*screen|inspect.*screen|read.*screen|what am i looking at|analyze.*screen|solve.*on.*screen|summarize.*page|read.*page|what.*open)/.test(t);
  if (wantsScreen) {
    const frame = grabVisionFrame();
    const bp = ui.browserPage;
    const openWins = ui.windows.filter((w) => !w.min).map((w) => appMeta(w.id).name);
    const topNote = prof?.notes[0];
    const thought = `Captured visual frame (${ui.visionActive ? `Live Display Stream ${ui.visionRes}` : "Singularity Workspace Canvas 640×360"}). Inspecting active windows (${openWins.join(", ") || "Desktop"}), Portal DOM buffer, and Vault state.`;

    // If the user also wants us to summarize or take notes on what's on screen:
    if (/(summarize|note|save|study|work|flashcard)/.test(t)) {
      const sourceTitle = bp.url ? bp.title : topNote ? topNote.title : "Workspace Screen Capture";
      const sourceBody = bp.content
        ? `## Screen & Page Summary: ${bp.title}\n**Source:** ${bp.url}\n\n${bp.content.slice(0, 1200)}\n\n### Key Takeaways\n- Extracted live from Portal Proxy buffer by KALMIA Vision.\n- Active windows during capture: ${openWins.join(", ") || "Desktop"}.`
        : `## Workspace Snapshot Notes\n- **Open Applications:** ${openWins.join(", ") || "Desktop"}\n- **Reactor Mass:** ${fmt(prof?.clicker.count ?? 0)}\n- **Latest Note:** ${topNote?.title || "None"}\n- **Pending Tasks:** ${(prof?.todos || []).filter((x) => !x.done).map((x) => x.text).join("; ") || "All clear"}`;
      actions.push(saveNoteToVault(`Vision Summary: ${sourceTitle}`, sourceBody, "vision"));
    }

    return {
      thought,
      screenshot: frame,
      actions,
      text: [
        `**KALMIA Screen Vision Report** (${ui.visionActive ? `Live Display Feed · ${ui.visionRes}` : "OS Workspace Vision"}):`,
        `• **Visible Windows:** ${openWins.length ? openWins.map((w) => `**${w}**`).join(", ") : "Clean desktop (no open windows)"}`,
        `• **Portal Browser State:** ${bp.url ? `Viewing **${bp.title}** (\`${bp.url}\`)` : "On Portal Start Page"}`,
        bp.content ? `• **Page Text Detected:** *"${bp.content.slice(0, 260).replace(/\s+/g, " ")}…"*` : "",
        topNote ? `• **Active Vault Note:** **${topNote.title}** (${topNote.body.split(/\s+/).length} words)` : "",
        `• **Reactor Telemetry:** **${fmt(prof?.clicker.count ?? 0)}** mass at **${ui.fps} FPS**`,
        actions.length ? `\nI also saved a structured summary directly to your **Vault**.` : `\nTell me **"summarize this into my notes"**, **"make flashcards from this page"**, or **"solve the problem on screen"** and I'll do the work automatically.`,
      ].filter(Boolean).join("\n"),
      chips: ["summarize screen to vault", "make flashcards from screen", "create tasks from screen"],
    };
  }

  // 2. Autonomous Workspace Setup ("set up study mode", "do my work", "focus workspace")
  if (/(study mode|focus mode|work mode|set up.*workspace|lock in)/.test(t)) {
    setS({ theme: "cryo", shader: "aurora" });
    openApp("notes");
    openApp("tools");
    const badge = addTodosToVault([
      "Complete 25-minute Pomodoro block in Toolbox",
      "Review key concepts in Vault study guide",
      "Test recall with KALMIA flashcards",
    ]);
    actions.push(badge, { label: "Switched to Cryo + Aurora Focus Theme", app: "modules" });
    return {
      thought: "Executing multi-step workspace automation: switching theme to Cryo, activating Aurora shader, queueing focus checklist in Vault, and opening study tools.",
      actions,
      text: "**Focus Workspace Engaged.**\n• Switched environment to **Cryo / Aurora**\n• Added a 3-step study checklist to your **Vault**\n• Opened **Vault** and **Toolbox** side-by-side.\n\nGive me your topic or homework prompt and I'll draft the notes or solve the problems for you.",
      chips: ["write a study guide on cellular respiration", "open portal", "inspect my screen"],
    };
  }

  // 3. Autonomous Essay / Study Guide / Summary / Flashcard Writer -> Saves directly to Vault!
  if (/(write|draft|create|make|generate)\s+(an?\s+)?(essay|report|paper|paragraph|study guide|guide|flashcards|summary|notes)\b/.test(t) || /^summarize\b/.test(t)) {
    const isFlash = /flashcard/.test(t);
    const isGuide = /(study guide|guide|notes|summary|^summarize)/.test(t);
    const bp = ui.browserPage;
    // If summarizing screen/page and browser has content:
    if (/screen|page|article|portal/.test(t) && bp.content) {
      const title = `Summary: ${bp.title}`;
      const body = `# ${bp.title}\n**Source:** ${bp.url}\n\n## Key Summary\n${bp.content.slice(0, 1800)}\n\n## Actionable Takeaways\n- Captured and distilled by KALMIA from your active Portal tab.`;
      actions.push(saveNoteToVault(title, body, "summary"));
      return {
        thought: `Reading active Portal buffer (${bp.content.length} chars) and synthesizing structured notes into Vault.`,
        actions,
        text: `I read **${bp.title}** from your Portal browser and saved a clean summary to your **Vault**.\n\n### Preview\n${body.slice(0, 500)}…`,
        chips: ["open vault", "make flashcards from this"],
      };
    }
    const doc = generateEssayOrGuide(q, isFlash ? "flashcards" : isGuide ? "guide" : "essay");
    actions.push(saveNoteToVault(doc.title, doc.body, isFlash ? "flashcards" : isGuide ? "study" : "essay"));
    return {
      thought: `Synthesizing ${isFlash ? "flashcard deck" : isGuide ? "structured study guide" : "multi-paragraph analytical essay"} on "${doc.title}" and committing to Vault storage.`,
      actions,
      text: `I completed **${doc.title}** and saved the full document into your **Vault**.\n\n---\n${doc.body}`,
      chips: ["open vault", "add study tasks for this", "quiz me on this"],
    };
  }

  // 4. Code / Mini-App / Game Builder (KALMIA-Code or "build/code/create a game/app/widget")
  if (persona === "kalmia-code" || /(build|code|program|create|make)\s+(me\s+)?(a\s+|an\s+)?(game|app|widget|pong|calculator|simulation|sandbox|html)/.test(t)) {
    const built = generateInteractiveCode(q);
    actions.push(saveCustomGame(built.title, built.html));
    return {
      thought: `Compiling self-contained HTML5/Canvas interactive bundle (${built.html.length} bytes) and mounting live sandbox preview + Arcade installer.`,
      actions,
      codePreview: built.html,
      text: `**${built.title}** is ready. ${built.summary}\n\nYou can play it right inside the live preview below, or launch it any time from **Singularity Arcade → Custom Studio**.`,
      chips: ["open arcade", "build a pong game", "build a star dodger game"],
    };
  }

  // 5. Math / Algebra / Equation / Calculation Solver with Step-by-Step Work
  const mathSolved = solveMathWork(q);
  if (mathSolved) {
    return {
      thought: `Running symbolic & numerical solver on "${q}".`,
      text: `### Step-by-Step Solution\n${mathSolved.steps}\n\n**Final Answer:** \`${mathSolved.answer}\``,
      chips: ["save solution to vault", "open calculator"],
    };
  }

  // 6. OS Commands: Open apps, switch themes/shaders, reactor clicks, notes, todos, stealth
  const openMatch = t.match(/^(?:open|launch|start|run|show)\s+(?:the\s+)?(.+)$/);
  if (openMatch) {
    const id = appByName(openMatch[1]);
    if (id) {
      openApp(id);
      return {
        actions: [{ label: `Launched ${appMeta(id).name}`, app: id }],
        text: `Opened **${appMeta(id).name}** — ${appMeta(id).desc}.`,
      };
    }
  }

  if (/^(theme|skin)\b/.test(t) || /(change|switch|set).*(theme|look)/.test(t)) {
    const found = THEMES.find((x) => t.includes(x.id) || t.includes(x.name.toLowerCase()));
    if (found) {
      runCommand("theme " + found.id);
      return {
        actions: [{ label: `Theme → ${found.name}`, app: "modules" }],
        text: `Switched system theme to **${found.name}** (${found.blurb}).`,
      };
    }
    return { text: "Available themes: " + THEMES.map((x) => `**${x.id}**`).join(" · "), chips: ["theme sakura", "theme cryo", "theme phosphor"] };
  }

  if (/(shader|background|visual)/.test(t) && SHADERS.some((x) => t.includes(x.id) || t.includes(x.name.toLowerCase()))) {
    const found = SHADERS.find((x) => t.includes(x.id) || t.includes(x.name.toLowerCase()))!;
    runCommand("shader " + found.id);
    return {
      actions: [{ label: `Shader → ${found.name}`, app: "modules" }],
      text: `Background renderer set to **${found.name}** — ${found.desc}.`,
    };
  }

  const colorMatch = t.match(/(?:accent|colou?r)\s+(?:to\s+)?(#?[0-9a-f]{6}|\w+)/);
  if (colorMatch) {
    const w = colorMatch[1];
    const hex = w.startsWith("#") ? w : COLOR_WORDS[w];
    if (hex) {
      runCommand("accent " + hex);
      return { text: `Accent colour locked to \`${hex}\`.` };
    }
  }

  const clickMatch = t.match(/^click(?:\s+(\d+))?/) || t.match(/^(?:mine|farm|grind|harvest)\s+(\d+)/);
  if (clickMatch) {
    const n = Math.min(25000, parseInt(clickMatch[1] || "100", 10));
    runCommand("click " + n);
    return {
      actions: [{ label: `Harvested ${n}× Reactor Clicks`, app: "core" }],
      text: `Fired the reactor **${fmt(n)}×**. Mass is now **${fmt(useOS.getState().db.profiles[os.session!]?.clicker.count ?? 0)}**.`,
    };
  }

  if (/^(note|remember|write down|log)\s+(.+)/.test(t)) {
    const body = q.replace(/^(note|remember|write down|log)\s+/i, "");
    const badge = saveNoteToVault(body.slice(0, 42), body, "quick");
    return { actions: [badge], text: `Saved to your **Vault**: "${body}"` };
  }

  if (/^(todo|task|remind me to|add task)\s+(.+)/.test(t)) {
    const body = q.replace(/^(todo|task|remind me to|add task)\s+/i, "");
    const badge = addTodosToVault([body]);
    return { actions: [badge], text: `Added task to your **Vault**: **${body}**` };
  }

  if (/(panic|hide|stealth|teacher|boss)/.test(t)) {
    ui.setStealth(true);
    return { text: "Stealth screen engaged. Press **Shift + S** to return." };
  }

  if (/(status|system report|telemetry|diagnostics)/.test(t)) {
    return {
      thought: "Querying Singularity OS kernel & mesh telemetry.",
      text: `### KALMIA System Diagnostics\n\`\`\`\n${getWorkspaceContext()}\n\`\`\``,
      chips: ["inspect my screen", "set up focus workspace", "open overwatch"],
    };
  }

  // 7. General Knowledge / Question Answering Fallback (never says "I don't have a routine"!)
  return {
    thought: `Analyzed request "${q.slice(0, 60)}" using KALMIA local knowledge synthesis.`,
    text: [
      `### ${q.charAt(0).toUpperCase() + q.slice(1)}`,
      `Here is a structured breakdown and analysis:`,
      ``,
      `• **Core Principle:** At its foundation, this topic centers on how primary mechanisms, context, and structural rules interact to produce observable outcomes.`,
      `• **Key Analysis:** When breaking down *${q.replace(/\?+$/, "")}*, the most important factors are causal drivers, quantifiable patterns, and practical trade-offs.`,
      `• **Actionable Next Step:** Want me to **save a full essay or study guide** on this into your Vault, **search live sources in Portal**, or **build an interactive demo**?`,
    ].join("\n"),
    chips: [
      `write an essay on ${q.replace(/\?+$/, "").slice(0, 28)}`,
      `make flashcards on ${q.replace(/\?+$/, "").slice(0, 28)}`,
      `inspect my screen`,
    ],
  };
}

/** Parse and execute `[ACTION:...]` tags emitted by the Cloud LLM so it can actually do work in the OS! */
function executeCloudActions(rawText: string): { cleanText: string; actions: AIActionBadge[]; codePreview?: string } {
  const actions: AIActionBadge[] = [];
  let cleanText = rawText;
  let codePreview: string | undefined;

  // [ACTION:SAVE_NOTE:Title]Body[/ACTION]
  cleanText = cleanText.replace(/\[ACTION:SAVE_NOTE:([^\]]+)\]([\s\S]*?)\[\/ACTION\]/gi, (_, title, body) => {
    actions.push(saveNoteToVault(title.trim(), body.trim(), "kalmia"));
    return `\n\n> ✓ **Saved to Vault:** *${title.trim()}*\n\n${body.trim()}\n`;
  });

  // [ACTION:ADD_TODO:Task text]
  cleanText = cleanText.replace(/\[ACTION:ADD_TODO:([^\]]+)\]/gi, (_, task) => {
    actions.push(addTodosToVault([task.trim()]));
    return "";
  });

  // [ACTION:OPEN_APP:appId]
  cleanText = cleanText.replace(/\[ACTION:OPEN_APP:([a-z]+)\]/gi, (_, id) => {
    const appId = appByName(id.trim());
    if (appId) {
      openApp(appId);
      actions.push({ label: `Opened ${appMeta(appId).name}`, app: appId });
    }
    return "";
  });

  // Extract ```html ... ``` code blocks for live preview!
  const htmlMatch = cleanText.match(/```html\s*([\s\S]*?)```/i);
  if (htmlMatch && htmlMatch[1].includes("<")) {
    codePreview = htmlMatch[1].trim();
    actions.push(saveCustomGame("Kalmia Live App", codePreview));
  }

  return { cleanText: cleanText.trim(), actions, codePreview };
}

/**
 * Cloud + Vision LLM router.
 * Supports:
 * 1. Free keyless Pollinations OpenAI endpoint (`https://text.pollinations.ai/openai`) with text + vision!
 * 2. Any OpenAI-compatible provider (OpenAI, Groq, OpenRouter, Ollama)
 * 3. Automatic seamless fallback to `novaRespond()` if offline or blocked!
 */
export async function kalmiaCompletion(
  history: ChatMsg[],
  s: Settings,
  opts: { attachVision?: boolean; signal?: AbortSignal } = {}
): Promise<NovaReply> {
  const lastUser = history[history.length - 1]?.text || "";
  const screenshot = opts.attachVision ? grabVisionFrame() : undefined;

  // Check if it's an immediate OS command first (like "theme sakura", "open arcade", "panic")
  if (/^(open|launch|theme|shader|accent|click|panic|cloak)\b/i.test(lastUser.trim())) {
    const local = novaRespond(lastUser, opts.attachVision);
    return { ...local, screenshot: screenshot || local.screenshot };
  }

  if (!s.aiCloud) {
    return novaRespond(lastUser, opts.attachVision);
  }

  const base = (s.aiBase || "https://text.pollinations.ai/openai").replace(/\/$/, "");
  const isPollinations = base.includes("pollinations.ai");
  const url = base.endsWith("/chat/completions") ? base : `${base}/chat/completions`;

  const sysPrompt = [
    s.aiSystem,
    `Active Persona: ${s.aiPersona.toUpperCase()} (Kalmia 4.0 Autonomous Vision & Work Agent inside Singularity OS).`,
    `LIVE WORKSPACE & SCREEN TELEMETRY:\n${getWorkspaceContext()}`,
    `AUTONOMOUS ACTION TAGS YOU CAN EMIT WHEN ASKED TO DO WORK:`,
    `- When asked to write/save an essay, note, summary, or study guide to the user's Vault, wrap it in: [ACTION:SAVE_NOTE:Title Here]Full markdown content here[/ACTION]`,
    `- When asked to add tasks/todos, emit: [ACTION:ADD_TODO:Task description]`,
    `- When asked to open an OS app (core, games, browser, tools, notes, terminal, music, modules, share), emit: [ACTION:OPEN_APP:id]`,
    `- When asked to build a playable mini-game or interactive widget, include a complete self-contained \`\`\`html ... \`\`\` block.`,
  ].join("\n\n");

  const messages: any[] = [
    { role: "system", content: sysPrompt },
    ...history.slice(-10, -1).map((m) => ({
      role: m.role === "ai" ? "assistant" : "user",
      content: m.text,
    })),
  ];

  // Attach vision image if present!
  if (screenshot && screenshot.startsWith("data:image")) {
    messages.push({
      role: "user",
      content: [
        { type: "text", text: lastUser || "Analyze what is on my screen and help me with it." },
        { type: "image_url", image_url: { url: screenshot } },
      ],
    });
  } else {
    messages.push({ role: "user", content: lastUser });
  }

  try {
    const ctl = new AbortController();
    const timeout = window.setTimeout(() => ctl.abort(), 14000);
    if (opts.signal) opts.signal.addEventListener("abort", () => ctl.abort());

    const res = await fetch(url, {
      method: "POST",
      signal: ctl.signal,
      headers: {
        "Content-Type": "application/json",
        ...(s.aiKey && !isPollinations ? { Authorization: `Bearer ${s.aiKey}` } : {}),
      },
      body: JSON.stringify({
        model: isPollinations ? "openai" : (s.aiModel || "gpt-4o-mini"),
        messages,
        temperature: 0.7,
      }),
    });
    window.clearTimeout(timeout);

    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json();
    const rawReply = data?.choices?.[0]?.message?.content?.trim();
    if (!rawReply) throw new Error("Empty completion");

    const { cleanText, actions, codePreview } = executeCloudActions(rawReply);
    return {
      text: cleanText,
      thought: `Processed via KALMIA-4 (${isPollinations ? "Pollinations Neural Cloud" : s.aiModel})${screenshot ? " + Live Screen Vision Frame" : ""} · Workspace context synced.`,
      screenshot,
      actions,
      codePreview,
      chips: ["save this to vault", "inspect my screen", "make flashcards from this"],
    };
  } catch {
    // Seamless offline / firewall fallback to Kalmia Local Work Engine!
    const fallback = novaRespond(lastUser, opts.attachVision);
    return {
      ...fallback,
      screenshot: screenshot || fallback.screenshot,
    };
  }
}

