/** Build a rich snapshot of what's currently on the user's screen & OS workspace. */
export function getWorkspaceContext(): string {
  const os = useOS.getState();
  const ui = useUI.getState();
  const prof = os.session ? os.db.profiles[os.session] : null;
  const openWins = ui.windows.filter((w) => !w.min).map((w) => appMeta(w.id).name);
  const topNote = prof?.notes[0];
  const pendingTodos = (prof?.todos || []).filter((t) => !t.done).slice(0, 6).map((t) => t.text);
  const bp = ui.browserPage;

  return [
    `User: ${os.session || "guest"}`,
    `Active Theme: ${prof?.settings.theme || "ember"} | Shader: ${prof?.settings.shader || "blackhole"} | FPS: ${ui.fps}`,
    `Open Windows on Screen: ${openWins.length ? openWins.join(", ") : "Desktop (no windows open)"}`,
    `Focused Window: ${ui.focused ? appMeta(ui.focused).name : "Desktop"}`,
    `Reactor Mass: ${fmt(prof?.clicker.count ?? 0)} (${fmt(perSecond(prof?.clicker ?? ({ drones: 0, reactors: 0, prestige: 0, folds: 0 } as any)))}/s passive)`,
    `Portal Browser Active Page: "${bp.title}" (${bp.url || "start page"})`,
    bp.content ? `Portal Page Content Excerpt:\n${bp.content.slice(0, 1400)}` : "",
    topNote ? `Latest Vault Note ("${topNote.title}"):\n${topNote.body.slice(0, 600)}` : "",
    pendingTodos.length ? `Pending Tasks: ${pendingTodos.join(" | ")}` : "Pending Tasks: None",
    `Live Screen Stream Linked: ${ui.visionActive ? `Yes (${ui.visionRes})` : "Using OS Workspace Vision"}`,
  ].filter(Boolean).join("\n");
}

/** Save a note into the user's Vault and return an action badge. */
export function saveNoteToVault(title: string, body: string, tag = "kalmia"): AIActionBadge {
  const os = useOS.getState();
  os.updateProfile((p) => ({
    ...p,
    notes: [{ id: uid(), title, body, tag, pinned: true, ts: Date.now() }, ...p.notes],
  }));
  return { label: `Saved Note: "${title.slice(0, 32)}"`, app: "notes", detail: tag };
}

/** Add one or more tasks to the user's Vault todos. */
export function addTodosToVault(items: string[]): AIActionBadge {
  const os = useOS.getState();
  os.updateProfile((p) => ({
    ...p,
    todos: [
      ...items.map((text) => ({ id: uid(), text, done: false, pri: 1 as const, ts: Date.now() })),
      ...p.todos,
    ],
  }));
  return { label: `Added ${items.length} Task(s) to Vault`, app: "notes" };
}

/** Save a generated HTML5 game/app into Singularity Arcade. */
export function saveCustomGame(name: string, html: string, blurb = "Generated by KALMIA-Code"): AIActionBadge {
  const os = useOS.getState();
  os.updateProfile((p) => ({
    ...p,
    customGames: [{ id: "cg-" + uid(), name, tag: "AI Built", blurb, html, created: Date.now() }, ...(p.customGames || [])],
  }));
  return { label: `Installed "${name}" in Arcade`, app: "games" };
}

/** Solve quadratic or linear equations & common calculus/stats expressions step-by-step. */
function solveMathWork(raw: string): { steps: string; answer: string } | null {
  const q = raw.trim();
  // Check for quadratic ax^2 + bx + c = 0
  const quad = q.replace(/\s+/g, "").match(/^([+-]?\d*\.?\d*)x\^2([+-]\d*\.?\d*)x([+-]\d+\.?\d*)=0$/i);
  if (quad) {
    const a = quad[1] === "" || quad[1] === "+" ? 1 : quad[1] === "-" ? -1 : parseFloat(quad[1]);
    const b = quad[2] === "+" ? 1 : quad[2] === "-" ? -1 : parseFloat(quad[2]);
    const c = parseFloat(quad[3]);
    const disc = b * b - 4 * a * c;
    const steps = [
      `1. **Identify coefficients** from \`${a}x² + (${b})x + (${c}) = 0\`:`,
      `   • \`a = ${a}\`, \`b = ${b}\`, \`c = ${c}\``,
      `2. **Compute the discriminant** \`Δ = b² - 4ac\`:`,
      `   • \`Δ = (${b})² - 4(${a})(${c}) = ${b * b} - ${4 * a * c} = ${disc}\``,
      disc >= 0
        ? `3. **Apply the quadratic formula** \`x = (-b ± √Δ) / (2a)\`:`
        : `3. **Complex roots** since \`Δ < 0\`:`,
    ].join("\n");
    if (disc >= 0) {
      const x1 = (-b + Math.sqrt(disc)) / (2 * a);
      const x2 = (-b - Math.sqrt(disc)) / (2 * a);
      return { steps, answer: x1 === x2 ? `x = ${+x1.toFixed(4)}` : `x₁ = ${+x1.toFixed(4)},  x₂ = ${+x2.toFixed(4)}` };
    } else {
      const re = (-b / (2 * a)).toFixed(3);
      const im = (Math.sqrt(-disc) / (2 * a)).toFixed(3);
      return { steps, answer: `x = ${re} ± ${im}i` };
    }
  }

  // Linear equation ax + b = c
  const lin = q.replace(/\s+/g, "").match(/^([+-]?\d*\.?\d*)x([+-]\d+\.?\d*)=([+-]?\d+\.?\d*)$/i);
  if (lin) {
    const a = lin[1] === "" || lin[1] === "+" ? 1 : lin[1] === "-" ? -1 : parseFloat(lin[1]);
    const b = parseFloat(lin[2]);
    const c = parseFloat(lin[3]);
    const rhs = c - b;
    const x = rhs / a;
    return {
      steps: `1. Subtract \`${b}\` from both sides: \`${a}x = ${c} - (${b}) = ${rhs}\`\n2. Divide by \`${a}\`: \`x = ${rhs} / ${a}\``,
      answer: `x = ${+x.toFixed(6)}`,
    };
  }

  // Direct arithmetic / scientific expression
  const expr = q.replace(/^(solve|calculate|calc|what is|evaluate|compute|=)\s*/i, "").replace(/\?+$/, "");
  const val = evalMath(expr);
  if (val !== null && /[0-9]/.test(expr)) {
    return {
      steps: `• Parsed expression: \`${expr}\`\n• Evaluated using IEEE-754 floating-point & Math kernel`,
      answer: `${val}`,
    };
  }
  return null;
}

